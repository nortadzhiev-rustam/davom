export function setLang(l) {
  if (LANGS.includes(l)) lang = l;
}

export function getLang() {
  return lang;
}

export function guessLang() {
  const n = (navigator.language || 'en').toLowerCase();
  if (n.startsWith('tr')) return 'tr';
  if (n.startsWith('uz')) return 'uz';
  if (n.startsWith('tg')) return 'tg';
  return 'en';
}

export function t(key, vars) {
  let s = STR[lang][key] ?? STR.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split('{' + k + '}').join(String(v));
  return s;
}

const numFormats = {};
export function fmtNum(n) {
  if (n == null || !Number.isFinite(n)) return '—';
  if (!numFormats[lang]) {
    try {
      numFormats[lang] = new Intl.NumberFormat(LOCALES[lang], { maximumFractionDigits: 2 });
    } catch {
      numFormats[lang] = new Intl.NumberFormat('en-US', { maximumFractionDigits: 2 });
    }
  }
  return numFormats[lang].format(n);
}

// For editable inputs: no thousands grouping, but the local decimal mark (12,5 in tr/uz/tg).
export function fmtInput(n) {
  if (!n) return '';
  fmtNum(0);
  const dec = (numFormats[lang].formatToParts(1.5).find((p) => p.type === 'decimal') || {}).value || '.';
  return String(n).replace('.', dec);
}

export function fmtPct(c) {
  if (c == null || !Number.isFinite(c)) return '—';
  const n = Math.round(c * 100);
  return lang === 'tr' ? '%' + n : n + '%';
}

const cal = () => CAL[lang];

export const dayShort = (s) => cal().dShort[D.dow(s)];
export const dayLong = (weekday) => cal().dLong[weekday];
export const fmtDayMonth = (s) => `${D.dayNum(s)} ${cal().mShort[D.monthIdx(s)]}`;
export const fmtDate = (s) => (s ? `${fmtDayMonth(s)} ${D.year(s)}` : '—');
export const fmtMonth = (s) => `${cal().mLong[D.monthIdx(s)]} ${D.year(s)}`;

export function fmtRange(a, b) {
  if (D.year(a) !== D.year(b)) return `${fmtDate(a)} – ${fmtDate(b)}`;
  if (D.monthIdx(a) !== D.monthIdx(b)) return `${fmtDayMonth(a)} – ${fmtDayMonth(b)} ${D.year(b)}`;
  return `${D.dayNum(a)}–${D.dayNum(b)} ${cal().mShort[D.monthIdx(b)]} ${D.year(b)}`;
}
